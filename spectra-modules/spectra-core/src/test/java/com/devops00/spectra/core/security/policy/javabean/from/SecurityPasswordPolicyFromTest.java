package com.devops00.spectra.core.security.policy.javabean.from;

import jakarta.validation.Validation;
import jakarta.validation.Validator;
import jakarta.validation.ValidatorFactory;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * 验证管理员不能配置超出支持上限的密码最小长度。
 *
 * @author yangxj96
 * @version 1.0
 * @since 2026/09/13
 */
class SecurityPasswordPolicyFromTest {

    private static ValidatorFactory validatorFactory;

    private static Validator validator;

    @BeforeAll
    static void setUpValidator() {
        validatorFactory = Validation.buildDefaultValidatorFactory();
        validator = validatorFactory.getValidator();
    }

    @AfterAll
    static void closeValidatorFactory() {
        validatorFactory.close();
    }

    @Test
    void shouldRejectMinimumLengthAboveSupportedMaximum() {
        SecurityPasswordPolicyFrom request = new SecurityPasswordPolicyFrom(21, true, true, true, true, null, 0L);

        assertTrue(validator.validateProperty(request, "minLength").iterator().hasNext());
    }
}
