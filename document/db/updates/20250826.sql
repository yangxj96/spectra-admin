CREATE TABLE SPECTRA.SYS_USER
(
    ID              NUMBER(19)    NOT NULL,

    NAME            VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    AVATAR          VARCHAR2(255),
    STATE           NUMBER(5),
    ORGANIZATION_ID NUMBER(19),
    PASSWORD        VARCHAR2(60)  NOT NULL,

    CREATED_BY      NUMBER(19),
    CREATED_AT      TIMESTAMP(6)  NOT NULL,
    UPDATED_BY      NUMBER(19),
    UPDATED_AT      TIMESTAMP(6)  NOT NULL,
    DELETED         TIMESTAMP(6)
);
COMMENT ON TABLE SPECTRA.SYS_USER IS '用户表';
COMMENT ON COLUMN SPECTRA.SYS_USER.NAME IS '姓名';
COMMENT ON COLUMN SPECTRA.SYS_USER.EMAIL IS '邮箱';
COMMENT ON COLUMN SPECTRA.SYS_USER.AVATAR IS '头像';
COMMENT ON COLUMN SPECTRA.SYS_USER.STATE IS '状态 0为假,非0为真';
COMMENT ON COLUMN SPECTRA.SYS_USER.ORGANIZATION_ID IS '组织机构ID';
COMMENT ON COLUMN SPECTRA.SYS_USER.PASSWORD IS '密码';
COMMENT ON COLUMN SPECTRA.SYS_USER.ID IS '主键ID';
COMMENT ON COLUMN SPECTRA.SYS_USER.CREATED_BY IS '创建人';
COMMENT ON COLUMN SPECTRA.SYS_USER.CREATED_AT IS '创建时间';
COMMENT ON COLUMN SPECTRA.SYS_USER.UPDATED_BY IS '最后更新人';
COMMENT ON COLUMN SPECTRA.SYS_USER.UPDATED_AT IS '最后更新时间';
COMMENT ON COLUMN SPECTRA.SYS_USER.DELETED IS '删除时间';


