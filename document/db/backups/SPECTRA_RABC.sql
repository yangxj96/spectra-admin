-- 账号表
CREATE TABLE "SPECTRA"."SYS_ACCOUNT"
(
    "ID"         NUMBER(19, 0)            NOT NULL,

    "USER_ID"    NUMBER(19, 0)            NOT NULL,
    "TYPE"       NUMBER(10, 0)            NOT NULL,

    "LOGIN_NAME" VARCHAR2(100),
    "PASSWORD"   VARCHAR2(255),
    "PHONE"      VARCHAR2(20),
    "EMAIL"      VARCHAR2(100),
    "OPENID"     VARCHAR2(100),
    "UNIONID"    VARCHAR2(100),
    "PROVIDER"   VARCHAR2(50),
    "STATUS"     NUMBER(1, 0)  DEFAULT 1  NOT NULL,
    "VERIFIED"   NUMBER(1, 0)  DEFAULT 0  NOT NULL,
    "EXPIRES_AT" TIMESTAMP WITH TIME ZONE,

    "CREATED_BY" NUMBER(19, 0),
    "CREATED_AT" TIMESTAMP WITH TIME ZONE NOT NULL,
    "UPDATED_BY" NUMBER(19, 0),
    "UPDATED_AT" TIMESTAMP WITH TIME ZONE NOT NULL,
    "DELETED"    TIMESTAMP WITH TIME ZONE,
    "VERSION"    NUMBER(19, 0) DEFAULT 0,

    CONSTRAINT chk_account_identifier CHECK
        (
        (TYPE = 1 AND LOGIN_NAME IS NOT NULL) OR
        (TYPE = 2 AND PHONE IS NOT NULL) OR
        (TYPE = 3 AND EMAIL IS NOT NULL) OR
        (TYPE = 4 AND OPENID IS NOT NULL)
        )
);
COMMENT ON TABLE SPECTRA.SYS_ACCOUNT IS '表说明';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."ID" IS '主键ID';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."CREATED_BY" IS '创建人';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."CREATED_AT" IS '创建时间';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."UPDATED_BY" IS '最后更新人';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."UPDATED_AT" IS '最后更新时间';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."DELETED" IS '删除时间';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."VERSION" IS '乐观锁';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."USER_ID" IS '用户ID';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."TYPE" IS '登录类型';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."LOGIN_NAME" IS '用户名（用于账号密码登录）';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."PASSWORD" IS '密码(仅用作账号密码登录)';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."PHONE" IS '手机号（用于短信登录）';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."EMAIL" IS '邮箱（用于邮箱验证码登录）';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."OPENID" IS '微信 openid';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."UNIONID" IS '微信 unionid（跨应用唯一）';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."PROVIDER" IS '第三方来源：WECHAT, ALIPAY, APPLE 等';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."STATUS" IS '1:正常 2:禁用 3:未验证';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."VERIFIED" IS '0:未验证 1:已验证（如手机号/邮箱）';
COMMENT ON COLUMN SPECTRA.SYS_ACCOUNT."EXPIRES_AT" IS '用于临时账号（如扫码未确认）';

CREATE UNIQUE INDEX "IDX_UK_SYS_ACCOUNT_ID" ON "SPECTRA"."SYS_ACCOUNT" (ID);
ALTER TABLE "SPECTRA"."SYS_ACCOUNT"
    ADD CONSTRAINT "PK_SYS_ACCOUNT_ID" PRIMARY KEY (ID) USING INDEX "IDX_UK_SYS_ACCOUNT_ID";
-- 用户名 索引
CREATE UNIQUE INDEX "UK_SYS_ACCOUNT_LOGIN_NAME" ON "SPECTRA"."SYS_ACCOUNT" (CASE WHEN DELETED IS NULL AND LOGIN_NAME IS NULL THEN LOGIN_NAME END);
-- 手机号 索引
CREATE UNIQUE INDEX "UK_SYS_ACCOUNT_PHONE" ON "SPECTRA"."SYS_ACCOUNT" (CASE WHEN DELETED IS NULL AND PHONE IS NULL THEN PHONE END);
-- OPENID 索引
CREATE UNIQUE INDEX "UK_SYS_ACCOUNT_OPENID" ON "SPECTRA"."SYS_ACCOUNT" (CASE WHEN DELETED IS NULL AND OPENID IS NULL THEN OPENID END);

