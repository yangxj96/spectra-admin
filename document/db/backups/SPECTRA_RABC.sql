-- 用户表
CREATE TABLE "SPECTRA"."SYS_USER"
(
    "ID"         NUMBER(19, 0)            NOT NULL,

    -- 核心身份
    "USERNAME"   VARCHAR2(100)            NOT NULL,
    "AVATAR"     VARCHAR2(255),
    "STATUS"     NUMBER(1, 0)  DEFAULT 1  NOT NULL,
    -- 扩展信息
    "REAL_NAME"  VARCHAR2(50),
    "GENDER"     NUMBER(1, 0)  DEFAULT 0,
    "BIRTHDAY"   DATE,
    "PHONE"      VARCHAR2(20),
    "EMAIL"      VARCHAR2(100),
    "COUNTRY"    VARCHAR2(50),
    "CITY"       VARCHAR2(50),
    "LANGUAGE"   VARCHAR2(10)  DEFAULT 'zh-CN',
    "TIMEZONE"   VARCHAR2(40)  DEFAULT 'Asia/Shanghai',

    "CREATED_BY" NUMBER(19, 0),
    "CREATED_AT" TIMESTAMP WITH TIME ZONE NOT NULL,
    "UPDATED_BY" NUMBER(19, 0),
    "UPDATED_AT" TIMESTAMP WITH TIME ZONE NOT NULL,
    "DELETED"    TIMESTAMP WITH TIME ZONE,
    "VERSION"    NUMBER(19, 0) DEFAULT 0
);

COMMENT ON TABLE SPECTRA.SYS_USER IS '用户表';
COMMENT ON COLUMN SPECTRA.SYS_USER."ID" IS '主键ID';
COMMENT ON COLUMN SPECTRA.SYS_USER."CREATED_BY" IS '创建人';
COMMENT ON COLUMN SPECTRA.SYS_USER."CREATED_AT" IS '创建时间';
COMMENT ON COLUMN SPECTRA.SYS_USER."UPDATED_BY" IS '最后更新人';
COMMENT ON COLUMN SPECTRA.SYS_USER."UPDATED_AT" IS '最后更新时间';
COMMENT ON COLUMN SPECTRA.SYS_USER."DELETED" IS '删除时间';
COMMENT ON COLUMN SPECTRA.SYS_USER."VERSION" IS '乐观锁';
COMMENT ON COLUMN SPECTRA.SYS_USER."USERNAME" IS '显示名称';
COMMENT ON COLUMN SPECTRA.SYS_USER."AVATAR" IS '头像';
COMMENT ON COLUMN SPECTRA.SYS_USER."STATUS" IS '状态 (1:正常 0:禁用)';
COMMENT ON COLUMN SPECTRA.SYS_USER."REAL_NAME" IS '真实姓名';
COMMENT ON COLUMN SPECTRA.SYS_USER."GENDER" IS '性别(0:保密)';
COMMENT ON COLUMN SPECTRA.SYS_USER."BIRTHDAY" IS '生日';
COMMENT ON COLUMN SPECTRA.SYS_USER."PHONE" IS '手机号';
COMMENT ON COLUMN SPECTRA.SYS_USER."EMAIL" IS '邮箱';
COMMENT ON COLUMN SPECTRA.SYS_USER."COUNTRY" IS '国家';
COMMENT ON COLUMN SPECTRA.SYS_USER."CITY" IS '城市';
